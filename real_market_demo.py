"""Score two rules using historical closes on the working test split."""
from pathlib import Path
from tempfile import TemporaryDirectory

from src.project import aggregate, evaluate, make_cases, write_csv

root = Path(__file__).resolve().parent
prices = root / "data/local/market_prices.csv"
output = root / "results/real_baselines"
cases = make_cases(prices, split="test")
# With no assistant submissions, evaluate scores only the two built-in baselines.
with TemporaryDirectory() as temp:
    empty_predictions = Path(temp) / "predictions.csv"
    write_csv(empty_predictions, [], ["prompt_id", "model", "predicted_return_pct"])
    details = evaluate(cases, predictions=empty_predictions, required_models=[])
scores = aggregate(details, ["horizon_trading_days", "model"])
write_csv(output / "metrics_by_horizon.csv", scores)

report = [
    "# Real market baseline backtest",
    "",
    f"{len(cases)} forecast cases across the S&P 500, Nasdaq-100, and Dow Jones Industrial Average.",
    "The working test split is the middle 20% of common dates. Origins are spaced 10 trading observations apart.",
    "Actual returns use observed closing levels. The zero-return rule predicts no change.",
    "The momentum rule uses the preceding return over the same number of trading observations.",
    "The forecasts are generated by rules. Assistant forecasts and parent-paper reproduction are outside this run.",
    "",
    "| Trading days | Rule | Cases | MAE (percentage points) |",
    "|---:|---|---:|---:|",
]
for row in scores:
    report.append(
        f"| {row['horizon_trading_days']} | {row['model']} | {row['n']} "
        f"| {row['mae_percentage_points']:.3f} |"
    )
report.extend([
    "",
    "Lower mean absolute error (MAE) indicates forecasts closer to actual returns.",
    "",
    "From the project folder on Windows, run:",
    "",
    "```bat",
    "py scripts/download_market_data.py",
    "py real_market_demo.py",
    "```",
    "",
    "Source: FRED daily closing series SP500, NASDAQ100, and DJIA. The input CSV stays local.",
])
report_text = "\n".join(report) + "\n"
(output / "REPORT.md").write_text(report_text, encoding="utf-8")
print(report_text)
